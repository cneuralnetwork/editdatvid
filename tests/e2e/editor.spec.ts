test('layers multiple video streams and mixes multiple audio tracks', async ({ page }, testInfo) => {
  test.skip(!existsSync('/usr/bin/ffmpeg'), 'The media fixture generator is unavailable.')
  const source = testInfo.outputPath('multistream-source.mp4')
  execFileSync('/usr/bin/ffmpeg', [
    '-loglevel', 'error', '-y', '-f', 'lavfi', '-i', 'testsrc=size=320x180:rate=15',
    '-f', 'lavfi', '-i', 'sine=frequency=523:sample_rate=48000', '-t', '2',
    '-c:v', 'libopenh264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', source,
  ])
  const errors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.addInitScript(() => { Object.defineProperty(window, 'showOpenFilePicker', { value: undefined, configurable: true }) })
  await page.goto('/')
  await page.getByRole('button', { name: 'New project' }).click()
  await page.getByLabel('Project name').fill('Multistream Check')
  await page.getByRole('button', { name: 'Create project' }).click()

  const chooser = page.waitForEvent('filechooser')
  await page.locator('.project-drop-empty').click()
  await (await chooser).setFiles(source)
  const asset = page.locator('.asset-row').filter({ hasText: 'multistream-source.mp4' })
  await expect(asset).toBeVisible()

  await asset.dblclick()
  await page.getByTitle('Target V2').click()
  await asset.dblclick()

  await expect(page.locator('.timeline-clip.video')).toHaveCount(2)
  await expect(page.locator('.timeline-clip.audio')).toHaveCount(2)
  await expect(page.locator('.timeline-track.video').nth(1).locator('.timeline-clip.video')).toHaveCount(1)
  await expect(page.locator('.timeline-track.video').nth(2).locator('.timeline-clip.video')).toHaveCount(1)
  await expect(page.locator('.timeline-track.audio').nth(0).locator('.timeline-clip.audio')).toHaveCount(1)
  await expect(page.locator('.timeline-track.audio').nth(1).locator('.timeline-clip.audio')).toHaveCount(1)
  await expect(page.locator('.program-media-layer')).toHaveCount(2)
  await expect(page.locator('.program-audio-layer')).toHaveCount(2)

  await page.locator('.program-monitor .play-control').click()
  await page.waitForTimeout(350)
  expect(await page.locator('.program-media-layer').evaluateAll((elements) => elements.every((element) => !(element as HTMLVideoElement).paused && (element as HTMLVideoElement).currentTime > 0))).toBe(true)
  expect(await page.locator('.program-audio-layer').evaluateAll((elements) => elements.every((element) => !(element as HTMLAudioElement).paused && (element as HTMLAudioElement).currentTime > 0))).toBe(true)
  await page.locator('.program-monitor .play-control').click()

  await page.getByLabel('Mute A2').click()
  await expect(page.locator('.program-audio-layer')).toHaveCount(1)
  await page.getByLabel('Hide V2').click()
  await expect(page.locator('.program-media-layer')).toHaveCount(1)
  expect(errors).toEqual([])
})

test('keeps title layers transparent and disposes deleted detached audio', async ({ page }, testInfo) => {
  test.skip(!existsSync('/usr/bin/ffmpeg'), 'The media fixture generator is unavailable.')
  const source = testInfo.outputPath('overlay-source.mp4')
  execFileSync('/usr/bin/ffmpeg', [
    '-loglevel', 'error', '-y', '-f', 'lavfi', '-i', 'testsrc=size=320x180:rate=15',
    '-f', 'lavfi', '-i', 'sine=frequency=659:sample_rate=48000', '-t', '2',
    '-c:v', 'libopenh264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', source,
  ])
  const errors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.addInitScript(() => { Object.defineProperty(window, 'showOpenFilePicker', { value: undefined, configurable: true }) })
  await page.goto('/')
  await page.getByRole('button', { name: 'New project' }).click()
  await page.getByLabel('Project name').fill('Overlay and Audio Check')
  await page.getByRole('button', { name: 'Create project' }).click()

  const chooser = page.waitForEvent('filechooser')
  await page.locator('.project-drop-empty').click()
  await (await chooser).setFiles(source)
  const asset = page.locator('.asset-row').filter({ hasText: 'overlay-source.mp4' })
  await asset.dblclick()
  await page.getByTitle('Target V2').click()
  await page.locator('.flexlayout__tab_button').filter({ hasText: /^Text$/ }).click()
  await page.getByRole('button', { name: 'Add title at playhead' }).click()

  await expect(page.locator('.program-media-layer')).toHaveCount(1)
  await expect(page.locator('.program-title')).toHaveCount(1)
  await expect.poll(() => page.locator('.program-media-layer').evaluate((element) => (element as HTMLVideoElement).readyState >= 2)).toBe(true)
  expect(await page.locator('.program-title').evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
  expect(await page.locator('.program-title > span').evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
  const overlayScreenshot = testInfo.outputPath('transparent-title-overlay.png')
  await page.locator('.program-frame').screenshot({ path: overlayScreenshot })
  const visibleVideoPixel = execFileSync('/usr/bin/ffmpeg', ['-loglevel', 'error', '-i', overlayScreenshot, '-vf', 'crop=1:1:iw/4:ih/4', '-frames:v', '1', '-f', 'rawvideo', '-pix_fmt', 'rgb24', 'pipe:1'])
  expect([...visibleVideoPixel].reduce((sum, value) => sum + value, 0)).toBeGreaterThan(30)

  const transformBox = page.getByTestId('program-transform-box')
  await expect(transformBox).toBeVisible()
  await expect(transformBox.getByRole('button', { name: 'Resize New Title from SE' })).toBeVisible()
  await expect(transformBox.getByRole('button', { name: 'Rotate New Title' })).toBeVisible()
  const originalBox = await transformBox.boundingBox()
  expect(originalBox).not.toBeNull()
  await page.mouse.move(originalBox!.x + originalBox!.width / 2, originalBox!.y + originalBox!.height / 2)
  await page.mouse.down()
  await page.mouse.move(originalBox!.x + originalBox!.width / 2 + 42, originalBox!.y + originalBox!.height / 2 + 24, { steps: 4 })
  await page.mouse.up()
  const movedBox = await transformBox.boundingBox()
  expect(movedBox!.x).toBeGreaterThan(originalBox!.x + 34)
  expect(movedBox!.y).toBeGreaterThan(originalBox!.y + 16)
  await page.keyboard.press('Control+z')
  await expect.poll(async () => (await transformBox.boundingBox())!.x).toBeLessThan(originalBox!.x + 3)

  const resizeHandle = transformBox.getByRole('button', { name: 'Resize New Title from SE' })
  const resizeHandleBox = await resizeHandle.boundingBox()
  await page.mouse.move(resizeHandleBox!.x + resizeHandleBox!.width / 2, resizeHandleBox!.y + resizeHandleBox!.height / 2)
  await page.mouse.down()
  await page.mouse.move(resizeHandleBox!.x + 60, resizeHandleBox!.y + 42, { steps: 4 })
  await page.mouse.up()
  const resizedBox = await transformBox.boundingBox()
  expect(resizedBox!.width).toBeGreaterThan(originalBox!.width * 1.25)

  const rotationHandle = transformBox.getByRole('button', { name: 'Rotate New Title' })
  const rotationHandleBox = await rotationHandle.boundingBox()
  const resizedCenter = { x: resizedBox!.x + resizedBox!.width / 2, y: resizedBox!.y + resizedBox!.height / 2 }
  await page.mouse.move(rotationHandleBox!.x + rotationHandleBox!.width / 2, rotationHandleBox!.y + rotationHandleBox!.height / 2)
  await page.mouse.down()
  await page.mouse.move(resizedCenter.x + 90, resizedCenter.y, { steps: 4 })
  await page.mouse.up()
  expect(await page.locator('.program-title > span').getAttribute('style')).not.toContain('rotate(0deg)')

  const videoClip = page.locator('.timeline-clip.video').filter({ hasText: 'overlay-source.mp4' })
  await videoClip.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Detach Audio' }).click()
  await expect(page.getByText('Audio detached. Video and audio now move independently.')).toBeVisible()
  const overlayPlayButton = page.locator('.program-monitor .play-control')
  await overlayPlayButton.click()
  await expect(overlayPlayButton).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => page.locator('.program-audio-layer').evaluate((element) => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(0)
  await page.locator('.program-audio-layer').evaluate((element) => { (window as typeof window & { detachedAudioUnderTest?: HTMLAudioElement }).detachedAudioUnderTest = element as HTMLAudioElement })
  await page.keyboard.press('Delete')

  await expect(page.locator('.program-audio-layer')).toHaveCount(0)
  const disposed = await page.evaluate(() => {
    const audio = (window as typeof window & { detachedAudioUnderTest?: HTMLAudioElement }).detachedAudioUnderTest
    return audio ? { paused: audio.paused, connected: audio.isConnected, source: audio.getAttribute('src') } : null
  })
  expect(disposed).toEqual({ paused: true, connected: false, source: null })
  expect(await page.locator('.program-media-layer').evaluate((element) => (element as HTMLVideoElement).muted)).toBe(true)

  await page.getByLabel('Hide V2').click()
  const programVideo = page.locator('.program-media-layer')
  await programVideo.click({ position: { x: 24, y: 24 } })
  await expect(page.getByTestId('program-transform-box')).toBeVisible()
  await expect(page.getByTestId('program-transform-box')).toContainText('Motion')
  const videoBox = await page.getByTestId('program-transform-box').boundingBox()
  await page.mouse.move(videoBox!.x + videoBox!.width / 2, videoBox!.y + videoBox!.height / 2)
  await page.mouse.down()
  await page.mouse.move(videoBox!.x + videoBox!.width / 2 + 28, videoBox!.y + videoBox!.height / 2 - 16, { steps: 3 })
  await page.mouse.up()
  expect(await programVideo.getAttribute('style')).not.toContain('translate(0px, 0px)')
  await page.getByLabel('Full-screen Program Monitor').click()
  await expect.poll(() => page.evaluate(() => document.fullscreenElement?.classList.contains('program-frame') ?? false)).toBe(true)
  await page.evaluate(() => document.exitFullscreen())
  await expect.poll(() => page.evaluate(() => document.fullscreenElement === null)).toBe(true)
  expect(errors).toEqual([])
})

test('generates and switches a local editing proxy in a worker', async ({ page }, testInfo) => {
  test.skip(!existsSync('/usr/bin/ffmpeg'), 'The proxy fixture generator is unavailable.')
  test.slow()
  const source = testInfo.outputPath('proxy-source.mp4')
  execFileSync('/usr/bin/ffmpeg', [
    '-loglevel', 'error', '-y', '-f', 'lavfi', '-i', 'testsrc=size=320x180:rate=10',
    '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000', '-t', '0.6',
    '-c:v', 'libopenh264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', source,
  ])
  const errors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.addInitScript(() => { Object.defineProperty(window, 'showOpenFilePicker', { value: undefined, configurable: true }) })
  await page.goto('/')
  await page.getByRole('button', { name: 'New project' }).click()
  await page.getByLabel('Project name').fill('Proxy Check')
  await page.getByRole('button', { name: 'Create project' }).click()
  const chooser = page.waitForEvent('filechooser')
  await page.locator('.project-drop-empty').click()
  await (await chooser).setFiles(source)
  await expect(page.locator('.asset-row').filter({ hasText: 'proxy-source.mp4' })).toBeVisible()
  await page.getByRole('button', { name: 'Generate proxy' }).click()
  await expect(page.getByRole('button', { name: 'Use original' })).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: 'Use original' }).click()
  await expect(page.getByRole('button', { name: 'Use proxy' })).toBeVisible()
  await page.locator('.asset-row').filter({ hasText: 'proxy-source.mp4' }).dblclick()
  await expect(page.locator('.timeline-clip.video')).toBeVisible()
  await page.locator('.timeline-clip.video').click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: 'Detach Audio' })).toBeEnabled()
  await page.getByRole('menuitem', { name: 'Detach Audio' }).click()
  await expect(page.getByText('Audio detached. Video and audio now move independently.')).toBeVisible()
  await page.getByRole('tab', { name: 'Export' }).click()
  await page.getByRole('button', { name: /WebM/ }).click()
  await page.locator('.export-detail select').selectOption('1280x720')
  const exportDownload = page.waitForEvent('download', { timeout: 60_000 })
  await page.getByRole('button', { name: 'Export to this device' }).click()
  const rendered = await exportDownload
  expect(rendered.suggestedFilename()).toBe('Proxy Check - Sequence 01.webm')
  const renderedPath = await rendered.path()
  expect(renderedPath).not.toBeNull()
  const dimensions = execFileSync('/usr/bin/ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', renderedPath!], { encoding: 'utf8' }).trim()
  expect(dimensions).toBe('1280,720')
  expect(errors).toEqual([])
})
